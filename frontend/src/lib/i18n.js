/**
 * Get translation for a key in the specified language.
 * Falls back to English if the key is not translated.
 *
 * @param {string} lang - Language code (e.g. "hi", "es", "en")
 * @param {string} key - Translation key (e.g. "chat.placeholder")
 * @returns {string} - Translated text
 */
export function translate(lang, key) {
  const dict = TRANSLATIONS[lang] || {};
  return dict[key] ?? UI_KEYS[key] ?? key;
}

/**
 * Get the language object by code.
 */
export function getLang(code) {
  return LANG_MAP[code] || LANG_MAP[DEFAULT_LANG];
}

